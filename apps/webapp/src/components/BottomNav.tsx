'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';

const NAV_ITEMS = [
  { href: '/dashboard', label: 'Home', icon: HomeIcon },
  { href: '/feed', label: 'Jobs', icon: JobsIcon },
  { href: '/cv', label: 'CV', icon: CVIcon },
  { href: '/applied', label: 'Applied', icon: AppliedIcon },
];

export function BottomNav() {
  const pathname = usePathname();

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 border-t border-[var(--border)] bg-[var(--bg-base)]/95 backdrop-blur-md md:hidden">
      <div className="flex items-center justify-around py-1.5 px-1">
        {NAV_ITEMS.map((item) => {
          const isActive = pathname === item.href || pathname.startsWith(item.href + '/');
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`bottom-nav-link mobile-touch relative hover-lift ${isActive ? 'active' : ''}`}
            >
              <item.icon className="h-5 w-5" aria-hidden="true" />
              <span className="mobile-text-lg">{item.label}</span>
            </Link>
          );
        })}
      </div>
      {/* Safe area padding for iOS */}
      <div className="h-safe-area-inset-bottom bg-[var(--bg-base)]" />
    </nav>
  );
}

